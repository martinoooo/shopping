export const PRODUCT_MAP = new Map(PRODUCTS.map((product) => [product.slug, product]))

export function getProductBySlug(slug: string | undefined): Product | undefined {
  return slug ? PRODUCT_MAP.get(slug) : undefined
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((product) => product.id === id)
}

export function getProductsByCategory(category: CategoryId): Product[] {
  return PRODUCTS.filter((product) => product.category === category)
}

export function getBestsellers(limit = 4): Product[] {
  return PRODUCTS.filter((product) => product.bestseller).slice(0, limit)
}

export function getNewArrivals(limit = 3): Product[] {
  return PRODUCTS.filter((product) => product.isNew).slice(0, limit)
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  const preferred = (product.pairsWith ?? [])
    .map((id) => getProductById(id))
    .filter((item): item is Product => item !== undefined && item.id !== product.id)
  const sameCategory = PRODUCTS.filter(
    (item) => item.category === product.category && item.id !== product.id && !preferred.some((p) => p.id === item.id),
  )
  return [...preferred, ...sameCategory].slice(0, limit)
}

export function getProductsByIds(ids: string[]): Product[] {
  return ids.map((id) => getProductById(id)).filter((product): product is Product => Boolean(product))
}

